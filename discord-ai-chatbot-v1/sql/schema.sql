-- Run in Supabase Dashboard -> SQL Editor.
-- Use the service_role/secret key only on the private backend (never in a client app).
-- RLS is enabled and no anon/authenticated policies are created.

create table if not exists public.guild_users (
    guild_id text not null,
    user_id text not null,
    username text not null default '',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    primary key (guild_id, user_id)
);

create table if not exists public.conversations (
    id bigint generated by default as identity primary key,
    guild_id text not null,
    channel_id text not null,
    user_id text not null,
    role text not null check (role in ('user', 'assistant')),
    content text not null,
    created_at timestamptz not null default now()
);

create index if not exists idx_conversations_context
on public.conversations (guild_id, channel_id, user_id, created_at desc);

create table if not exists public.memories (
    id bigint generated by default as identity primary key,
    guild_id text not null,
    user_id text not null,
    content text not null,
    content_hash text not null,
    category text not null default 'context'
        check (category in ('profile', 'preference', 'goal', 'project', 'context')),
    importance integer not null default 5 check (importance between 1 and 10),
    created_at timestamptz not null default now(),
    unique (guild_id, user_id, content_hash)
);

create index if not exists idx_memories_lookup
on public.memories (guild_id, user_id, importance desc, created_at desc);

create table if not exists public.guild_settings (
    guild_id text primary key,
    chat_enabled boolean not null default true,
    updated_at timestamptz not null default now()
);

alter table public.guild_users enable row level security;
alter table public.conversations enable row level security;
alter table public.memories enable row level security;
alter table public.guild_settings enable row level security;

-- Intentionally no public policies. Backend accesses these tables using
-- the Supabase secret/service-role key stored in .env on the VPS only.
